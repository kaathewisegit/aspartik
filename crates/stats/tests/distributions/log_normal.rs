#[test]
fn test_new_is_ok() {
	let cases = [
		(10.0, 0.1),
		(-5.0, 1.0),
		(0.0, 10.0),
		(10.0, 100.0),
		(-5.0, f64::INFINITY),
	];
	for args in cases {
		assert_new_is_ok(args);
	}
}

#[test]
fn test_new_is_err() {
	let cases = [
		((f64::NAN, 1.0), LogNormalError::LocationInvalid),
		((1.0, f64::NAN), LogNormalError::ScaleInvalid),
		((0.0, 0.0), LogNormalError::ScaleInvalid),
		((f64::NAN, f64::NAN), LogNormalError::LocationInvalid),
		((1.0, -1.0), LogNormalError::ScaleInvalid),
	];
	for (args, err) in cases {
		assert_new_is_err(args, err);
	}
}

