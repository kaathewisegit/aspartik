#[test]
fn test_sf() {
	let cases = [
		((0.0, 1.0), 0.0, 1.0), // test_neg_sf
	];
	for (args, p, expected) in cases {
		assert_exact(args, p, |d, p| d.sf(p), expected);
	}

	let abs_cases = [
		((-0.1, 0.1), 0.1, 1.0, 1e-107),
		((-0.1, 0.1), 0.8, 0.890919989231123, 1e-14),
		((1.5, 1.0), 0.8, 0.957568715612642, 1e-14),
		((2.5, 1.5), 0.1, 0.9993169594777358, 1e-14),
	];
	for (args, p, expected, epsilon) in abs_cases {
		let sf = new_dist(args).sf(p);
		assert_abs_diff_eq!(sf, expected, epsilon = epsilon)
	}
}

