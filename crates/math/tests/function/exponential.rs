use math::{assert_almost_eq, function::exponential::*};

#[test]
fn test_integral() {
	let cases = [
		((0.001, 1), 6.331539364136149, 1e-16),
		((0.1, 1), 1.8229239584193906, 1e-15),
		((1.0, 1), 0.21938393439552029, 1e-16),
		((2.0, 1), 0.048900510708061125, 1e-15),
		((2.5, 1), 0.02491491787026974, 1e-15),
		((10.0, 1), 4.156968929685325e-6, 1e-20),
		((0.001, 2), 0.9926689604692389, 1e-16),
		((0.1, 2), 0.7225450221940204, 1e-15),
		((1.0, 2), 0.14849550677592205, 1e-16),
		((2.0, 2), 0.03753426182049045, 1e-16),
		((10.0, 2), 3.830240465631608e-6, 1e-20),
		((0.001, 0), 999.000499833375, 1e-16),
		((0.1, 0), 9.048374180359595, 1e-16),
		((1.0, 0), 0.3678794411714423, 1e-16),
		((2.0, 0), 0.06766764161830635, 1e-16),
		((10.0, 0), 4.539992976248485e-6, 1e-16),
	];

	for ((x, n), expected, epsilon) in cases {
		assert_almost_eq!(
			ei(n, x).unwrap(),
			expected,
			epsilon = epsilon,
		);
	}
}
